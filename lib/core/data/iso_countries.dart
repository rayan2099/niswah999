/// Standard reference data (ISO 3166-1 country names, English and Arabic)
/// — not religious/demographic evidence, unlike
/// `MadhhabSuggestionService`'s mapping. Used by the Madhhab Resolution
/// Flow's searchable country pickers (Startup/Madhhab Resolution Gate wave)
/// so a user answering "where did you learn most of your religious
/// practice?" is never limited to a small, hard-coded list of
/// Muslim-majority countries — she can pick any country, and the
/// suggestion logic honestly reports insufficient evidence for any country
/// outside the reviewed mapping, rather than that mapping silently
/// constraining what she's even allowed to select.
///
/// Distinct from `kCountries` in `countries.dart`, which is a small,
/// dial-code-oriented list for phone-auth inputs — not reused here since
/// this needs full world coverage and an ISO code, not a dial code.
class IsoCountry {
  const IsoCountry(this.code, this.nameEn, this.nameAr);

  /// ISO 3166-1 alpha-2 code — the value actually stored/compared
  /// internally, never a translated display string (a name typed/selected
  /// in one language must never fail to match logic keyed by the other).
  final String code;
  final String nameEn;
  final String nameAr;

  @override
  bool operator ==(Object other) => other is IsoCountry && other.code == code;

  @override
  int get hashCode => code.hashCode;
}

